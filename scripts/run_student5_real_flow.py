"""Run recommend → confirm → preview on a real Student 4 output for one selected outfit.

Run from the repository root:

    uv run python -m scripts.run_student5_real_flow PATH/TO/ranked_outfits.json \\
        --select O0011 [--preview-mode FLAT_LAY] [--output-dir DIR]

- `recommend` runs on the Student 4 output with the same temporary 500 USD test request and
  wrapper as `scripts.run_student4_real_top3`.
- `--select` must be one of the current Top-3 outfit_ids; anything else stops before confirm.
- `confirm` runs with that exact outfit_id; `preview` runs only after a successful confirm, and
  only for that one outfit.
- Formal CLI runs automatically load the repository `.env`, require the real OpenAI provider and
  fail if the result is a mock or product-card fallback. Mock providers remain available only to
  offline unit tests through the Python function arguments.

Writes `confirmed_outfit.json` and `preview_result.json` (default:
`artifacts/student4_real_data/`, git-ignored). No API key or other environment value is read
for output, printed or saved; the service, adapter and scoring are used unchanged.

Exit codes: 0 only when confirm succeeds and a real OpenAI image file is generated; 1 otherwise.
"""

from __future__ import annotations

import argparse
import json
import os
import sys
from collections.abc import Callable
from pathlib import Path
from typing import Any

from dotenv import load_dotenv

from scripts.run_student4_real_top3 import (
    TEST_BUDGET_NOTE,
    build_payload,
    load_ranked_outfits,
)

DEFAULT_OUTPUT_DIR = Path("artifacts/student4_real_data")
REPO_ENV_FILE = Path(__file__).resolve().parents[1] / ".env"
PREVIEW_MODES = ("FLAT_LAY",)
PROVIDERS = ("server", "mock")
REQUIRED_REAL_PREVIEW_ENV = (
    "PREVIEW_PROVIDER",
    "PREVIEW_API_KEY",
    "PREVIEW_MODEL",
    "PREVIEW_ALLOWED_IMAGE_HOSTS",
)

ServiceRun = Callable[[dict], Any]


class FlowError(ValueError):
    """The flow cannot start (bad selection, mode or provider, or recommend failed)."""


def load_real_preview_environment(env_file: Path | None = None) -> None:
    """Load the repository's private .env and require a real OpenAI preview configuration."""
    env_file = REPO_ENV_FILE if env_file is None else env_file
    if not env_file.is_file():
        raise FlowError(f"real preview configuration file is missing: {env_file}")
    load_dotenv(env_file, override=False)
    missing = [name for name in REQUIRED_REAL_PREVIEW_ENV if not os.environ.get(name, "").strip()]
    if missing:
        raise FlowError(f"real preview configuration is incomplete; missing {missing}")
    if os.environ["PREVIEW_PROVIDER"].strip() != "openai":
        raise FlowError("PREVIEW_PROVIDER must be 'openai' for a formal run")


def require_real_preview(preview: dict) -> Path:
    """Return the generated image path, or fail when preview used mock/fallback output."""
    reference = preview.get("output_reference")
    output = Path(reference) if isinstance(reference, str) and reference else None
    real = (
        preview.get("preview_source") == "openai"
        and preview.get("preview_result_status") == "SUCCESS"
        and preview.get("image_generated") is True
        and output is not None
        and output.is_file()
    )
    if not real:
        raise FlowError(
            "formal run requires a real OpenAI preview image; mock and product-card fallback "
            "results are not accepted"
        )
    return output


def _service_run() -> ServiceRun:
    from travel_agent.recommendation.service import run

    return run


def image_generated(preview_source: str | None, preview: dict | None) -> bool:
    """True only for a real provider image: not mock, not the product-card fallback."""
    return bool(
        preview
        and preview_source not in (None, "mock", "product_card_fallback")
        and preview.get("status") == "SUCCESS"
        and preview.get("delivered_mode") not in (None, "PRODUCT_CARDS")
        and preview.get("output_reference")
    )


def _explanation(preview_source: str | None, generated: bool) -> str:
    if generated:
        return "A real AI preview image was generated by the configured provider."
    if preview_source == "mock":
        return "Mock provider: the flow was checked; no AI image was generated."
    if preview_source == "product_card_fallback":
        return (
            "No AI image was generated: the product-card fallback was returned (no real preview "
            "provider configured, or generation was unavailable)."
        )
    return "No AI image was generated."


def _check_options(preview_mode: str, provider: str) -> None:
    if preview_mode not in PREVIEW_MODES:
        raise FlowError(f"--preview-mode must be one of {list(PREVIEW_MODES)}")
    if provider not in PROVIDERS:
        raise FlowError(f"--provider must be one of {list(PROVIDERS)}")


def confirm_then_preview(
    data: dict,
    select: str,
    preview_mode: str = "FLAT_LAY",
    provider: str = "server",
    run: ServiceRun | None = None,
    note: str = TEST_BUDGET_NOTE,
) -> tuple[dict, dict]:
    """confirm `select` against the latest recommend result `data` (its `state` and
    `recommendation_set`), then preview it only if the confirm succeeded.

    Returns (confirmed_record, preview_record). A selection outside the current Top-3 raises
    FlowError before confirm is called.
    """
    _check_options(preview_mode, provider)
    run = run or _service_run()
    top3_ids = [r["outfit_id"] for r in data["recommendation_set"]["recommendations"]]
    if select not in top3_ids:
        raise FlowError(f"--select must be one of the current Top-3 {top3_ids}")

    confirmed = run(
        {
            "action": "confirm",
            "state": data["state"],
            "recommendation_set": data["recommendation_set"],
            "outfit_id": select,
        }
    )
    confirmed_data = confirmed.model_dump(mode="json")["data"] or {}
    confirmed_record = {
        "note": note,
        "selected_outfit_id": select,
        "top3_outfit_ids": top3_ids,
        "recommendation_round": data["state"]["recommendation_round"],
        "confirm_status": confirmed.status,
        "confirm_succeeded": confirmed.status == "ok",
        "confirm_reason": confirmed.reason,
        "session_status": (confirmed_data.get("state") or {}).get("session_status"),
        "confirmed_outfit": confirmed_data.get("confirmed_outfit"),
    }
    preview_record: dict[str, Any] = {
        "selected_outfit_id": select,
        "confirm_status": confirmed.status,
        "confirm_succeeded": confirmed.status == "ok",
        "preview_status": None,
        "preview_completed": False,
        "requested_mode": preview_mode,
        "delivered_mode": None,
        "preview_source": None,
        "provider_name": None,
        "output_reference": None,
        "warnings": [],
        "image_generated": False,
        "fallback_reason": None,
        "requested_provider": provider,
    }
    if confirmed.status != "ok":
        preview_record["explanation"] = "Preview was not run because confirm did not succeed."
        return confirmed_record, preview_record

    payload = {
        "action": "preview",
        "confirmed_outfit": confirmed_data["confirmed_outfit"],
        "preview_mode": preview_mode,
    }
    if provider == "mock":
        payload["preview_provider"] = "mock"
    previewed = run(payload)
    preview_data = previewed.model_dump(mode="json")["data"] or {}
    preview = preview_data.get("preview") or {}
    source = preview_data.get("preview_source")
    generated = image_generated(source, preview)
    warnings = preview.get("warnings", [])
    preview_record.update(
        preview_status=previewed.status,
        preview_completed=previewed.status == "ok",
        preview_reason=previewed.reason,
        preview_result_status=preview.get("status"),
        requested_mode=preview.get("requested_mode", preview_mode),
        delivered_mode=preview.get("delivered_mode"),
        preview_source=source,
        provider_name=preview.get("provider_name"),
        output_reference=preview.get("output_reference"),
        warnings=warnings,
        disclaimer=preview.get("disclaimer"),
        image_generated=generated,
        fallback_reason=" ".join(warnings) if preview.get("status") == "FALLBACK" else None,
        explanation=_explanation(source, generated),
    )
    return confirmed_record, preview_record


def run_flow(
    ranked_outfits: list,
    select: str,
    preview_mode: str = "FLAT_LAY",
    provider: str = "server",
    run: ServiceRun | None = None,
) -> tuple[dict, dict]:
    """recommend → confirm → preview; returns (confirmed_record, preview_record)."""
    _check_options(preview_mode, provider)
    run = run or _service_run()
    recommended = run(build_payload(ranked_outfits))
    if recommended.status != "ok":
        raise FlowError(f"recommend returned {recommended.status}: {recommended.reason}")
    data = recommended.model_dump(mode="json")["data"]
    return confirm_then_preview(data, select, preview_mode, provider, run)


def _write_json(path: Path, data: dict) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("ranked_outfits", type=Path, help="Student 4 output (JSON list)")
    parser.add_argument("--select", required=True, help="outfit_id from the current Top-3")
    parser.add_argument("--preview-mode", default="FLAT_LAY", choices=PREVIEW_MODES)
    parser.add_argument("--output-dir", type=Path, default=DEFAULT_OUTPUT_DIR)
    args = parser.parse_args(argv)

    try:
        load_real_preview_environment()
        confirmed, preview = run_flow(
            load_ranked_outfits(args.ranked_outfits), args.select, args.preview_mode, "server"
        )
    except FlowError as exc:
        print(f"error: {exc}")
        return 1
    _write_json(args.output_dir / "confirmed_outfit.json", confirmed)
    _write_json(args.output_dir / "preview_result.json", preview)
    try:
        generated_image = require_real_preview(preview)
    except FlowError as exc:
        print(f"error: {exc}")
        return 1
    print(f"confirm: {confirmed['confirm_status']} (session_status: {confirmed['session_status']})")
    print(
        f"preview: {preview['preview_status']} source={preview['preview_source']} "
        f"status={preview.get('preview_result_status')} requested={preview['requested_mode']} "
        f"delivered={preview['delivered_mode']} image_generated={preview['image_generated']}"
    )
    print(f"  {preview.get('explanation')}")
    for warning in preview["warnings"]:
        print(f"  warning: {warning}")
    print(f"saved: {(args.output_dir / 'confirmed_outfit.json').resolve()}")
    print(f"saved: {(args.output_dir / 'preview_result.json').resolve()}")
    print(f"generated image: {generated_image.resolve()}")
    ok = confirmed["confirm_status"] == "ok" and preview["preview_status"] == "ok"
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
